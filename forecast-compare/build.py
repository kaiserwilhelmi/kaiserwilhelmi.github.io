"""Build the single self-contained page: template.html + engine.js + worker.js + upload.js + mw.js + app.js -> index.html

The Series menu lists every Industry Market Watch series. Only the catalog (names,
units, publishers, industries) is built in here; the numbers themselves are loaded
from the Market Watch site when a series is picked, so they stay current.
Set MW_REPO to a local clone of kaiserwilhelmi/market-watch (default ../../market-watch)."""
import csv, json, os, sys

MW = os.environ.get("MW_REPO", os.path.join("..", "..", "market-watch"))
sys.path.insert(0, MW)
import series as mws   # noqa: E402  (market-watch/series.py)
import agency as mwa   # noqa: E402  (market-watch/agency.py)
import sources as mwsrc  # noqa: E402  (market-watch/sources.py: publisher page per series)

SERIES = [  # key, file, display name, unit, unit in sentences, source, sample?
    ("sample", "SAMPLE_demand.csv", "Sample demand", "units", "units", "SAMPLE: synthetic data generated by make_sample.py", True),
    ("spares", "SAMPLE_spares.csv", "Sample spare-part demand (many zero months)", "units", "units", "SAMPLE: synthetic data generated by make_sample.py", True),
]
data = []
for key, fn, name, unit, short, src, sample in SERIES:
    rows = list(csv.DictReader(open("data/" + fn)))
    data.append({"key": key, "name": name, "unit": unit, "short": short, "source": src, "sample": sample,
                 "dates": [r["date"] for r in rows], "values": [float(r["value"]) for r in rows]})

CUR = {"MXN": "Mexican pesos", "JPY": "yen", "TWD": "Taiwan dollars", "KRW": "won", "CNY": "yuan", "CAD": "Canadian dollars"}
def units(u):
    """(unit for the meta line, unit used in sentences)"""
    if u == "index": return "index", "index points"
    if u == "$/t": return "$ per metric ton", "$/metric ton"
    if u == "$/hr": return "$ per hour", "$/hour"
    if u == "USD": return "US$ per euro", "US$ per euro"
    if u in CUR: return CUR[u] + " per US$", u + " per US$"
    return u, u

ind_of = {}
for slug, iname, _, ids in mws.INDUSTRIES:
    for i in ids: ind_of.setdefault(i, []).append(iname)
iname = {slug: n for slug, n, _, _ in mws.INDUSTRIES}
for slug, ex in mwa.EXTRAS.items():
    for k in ex.get("spot", []): ind_of.setdefault("spot:" + k, []).append(iname[slug])

GROUPS = [("Materials", "Materials (producer prices)"), ("Commodities", "Commodities"), ("Energy", "Energy"),
          ("Freight & services", "Freight & services"), ("Labor", "Labor (hourly earnings)"), ("Currency", "Currency"),
          ("spot", "Recent spot prices (EIA, USDA)")]
items = []
for sid, (name, group, unit, _, pub) in mws.SERIES.items():
    assert os.path.exists(os.path.join(MW, "data", "long", sid + ".csv")), sid
    ul, us = units(unit)
    items.append({"k": "mw:" + sid, "id": sid, "n": name, "g": group, "u": ul, "s": us, "f": "month",
                  "avg": sid.startswith(mws.NON_MONTHLY), "p": mws.PUB[pub][0], "pu": mws.PUB[pub][1],
                  "src": mwsrc.series_url(sid), "ind": ind_of.get(sid, [])})
spot_rows = json.load(open(os.path.join(MW, "data", "agency", "spot.json")))
for key, (name, unit, freq, pub, *_rest) in mwa.SPOT.items():
    assert spot_rows.get(key), key
    items.append({"k": "sp:" + key, "id": key, "n": name + " · " + freq, "g": "spot", "u": unit, "s": unit, "f": freq,
                  "avg": False, "p": mwa.AGENCY_PUB[pub][0], "pu": mwa.AGENCY_PUB[pub][1], "src": _rest[-1],
                  "ind": ind_of.get("spot:" + key, [])})
assert {g for g, _ in GROUPS} >= {it["g"] for it in items}
# Featured series: nine published series used in forecasting textbooks and studies, embedded in the page.
# data/featured/SHA256SUMS pins the files; verify_featured.py checks them against a second copy of each source.
# key, file, name, unit (meta line), unit in sentences, seasonality, publisher credit, link, what it shows
FEATURED = [
    ("retail", "us_retail_sales_nsa_monthly.csv", "US retail sales, not seasonally adjusted", "$ millions", "$M", 12,
     "U.S. Census Bureau, Advance Monthly Retail Trade Survey (RSXFSN), via FRED, retrieved 25 Nov 2026",
     "https://fred.stlouisfed.org/series/RSXFSN",
     "A December peak every year, steady growth, the COVID drop in April 2020 and the stimulus jump in 2021."),
    ("airline", "airline_passengers_monthly.csv", "International airline passengers, 1949 to 1960", "thousands of passengers", "thousand passengers", 12,
     "Box &amp; Jenkins (1976), <i>Time Series Analysis: Forecasting and Control</i>, series G (Pan Am bookings), via R datasets",
     "https://stat.ethz.ch/R-manual/R-devel/library/datasets/html/AirPassengers.html",
     "The textbook seasonal series: a steady trend and a summer peak that grows with the level."),
    ("drugs", "pbs_antidiabetic_scripts_monthly.csv", "Antidiabetic drug sales, Australia", "$ millions", "$M", 12,
     "Australian Pharmaceutical Benefits Scheme (Medicare Australia), ATC group A10, via Hyndman &amp; Athanasopoulos, <i>fpp2</i> package",
     "https://pkg.robjhyndman.com/fpp2-package/reference/a10.html",
     "Fast growth with a January spike that gets bigger every year."),
    ("beer", "australian_beer_quarterly.csv", "Beer production, Australia", "megalitres", "ML", 4,
     "Australian Bureau of Statistics (CC BY 4.0), via Hyndman &amp; Athanasopoulos, <i>fpp2</i> package",
     "https://pkg.robjhyndman.com/fpp2-package/reference/ausbeer.html",
     "A strong quarterly pattern on a trend that rose, then flattened and turned down."),
    ("gasoline", "us_gasoline_weekly.csv", "US gasoline product supplied, weekly", "million barrels per day", "M bbl/day", 52,
     "U.S. Energy Information Administration, finished motor gasoline product supplied, via Hyndman &amp; Athanasopoulos, <i>fpp2</i> package",
     "https://pkg.robjhyndman.com/fpp2-package/reference/gasoline.html",
     "26 years of weekly data with a yearly cycle that is not a whole number of weeks (52.18). The slowest one to fit: about half a minute."),
    ("power", "victoria_electricity_daily.csv", "Electricity demand, Victoria (Australia), 2014", "gigawatts (daily average)", "GW", 7,
     "Australian Energy Market Operator (AEMO), half-hourly demand as published in Hyndman &amp; Athanasopoulos, <i>fpp2</i> package, averaged to days by me",
     "https://pkg.robjhyndman.com/fpp2-package/reference/elecdemand.html",
     "A weekday pattern plus a swing driven by summer heat, which a model of the series' own past can only partly follow."),
    ("walmart", "walmart_item_daily_intermittent.csv", "One Walmart item, daily unit sales (many zero days)", "units", "units", 7,
     "M5 competition data, Walmart via the University of Nicosia (Makridakis, Spiliotis &amp; Assimakopoulos, 2022), CC BY 4.0; item HOBBIES_1_006, store CA_1",
     "https://doi.org/10.5281/zenodo.12636070",
     "Slow-moving demand: no sale on 56% of days, often 1 to 3 units when it sells. The page ranks this kind of series by RMSE and never forecasts below zero. About 20 seconds to fit."),
    ("cad", "cad_per_usd_monthly.csv", "Canadian dollars per US dollar", "Canadian dollars per US$", "CAD per US$", 1,
     "Board of Governors of the Federal Reserve System, G.5 Foreign Exchange Rates (EXCAUS), via FRED, retrieved 25 Nov 2026",
     "https://fred.stlouisfed.org/series/EXCAUS",
     "An exchange rate. Like most traded prices it moves close to a random walk, so the honest answer is often the latest value."),
    ("nile", "nile_annual_flow.csv", "Nile river flow at Aswan, 1871 to 1970", "100 million cubic metres a year", "× 10⁸ m³", 1,
     "Cobb (1978), <i>Biometrika</i> 65(2); Durbin &amp; Koopman (2012), via R datasets",
     "https://stat.ethz.ch/R-manual/R-devel/library/datasets/html/Nile.html",
     "A short yearly series with no seasons and a lasting drop in level around 1898."),
]
feat = []
for key, fn, name, unit, short, m, pub, url, note in FEATURED:
    rows = list(csv.DictReader(open("data/featured/" + fn)))
    feat.append({"k": "ft:" + key, "n": name, "u": unit, "s": short, "m": m, "p": pub, "src": url, "note": note,
                 "dates": [r["date"] for r in rows], "values": [float(r["value"]) for r in rows]})

catalog = {"featured": feat, "groups": [{"k": g, "label": lab} for g, lab in GROUPS], "items": items}

page = open("template.html").read()
for tag, val in [("/*__DATA__*/null", json.dumps(data, separators=(",", ":"))),
                 ("/*__CATALOG__*/null", json.dumps(catalog, separators=(",", ":"), ensure_ascii=False)),
                 ("/*__COUNT__*/", str(len(items))),
                 ("/*__ENGINE__*/", open("engine.js").read()), ("/*__WORKER__*/", open("worker.js").read()), ("/*__UPLOAD__*/", open("upload.js").read()),
                 ("/*__MW__*/", open("mw.js").read()), ("/*__APP__*/", open("app.js").read())]:
    assert tag in page, tag
    page = page.replace(tag, val)
assert "/*__" not in page
open("index.html", "w").write(page)
print("index.html", len(page), "bytes;", len(feat), "featured +", len(items), "Market Watch series")

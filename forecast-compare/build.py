"""Build the single self-contained page: template.html + engine.js + app.js + data/*.csv -> index.html"""
import csv, json

SERIES = [  # key, file, display name, unit, unit in sentences, source, sample?
    ("sample", "SAMPLE_demand.csv", "Sample demand", "units", "units", "SAMPLE: synthetic data generated by make_sample.py", True),
    ("cass", "FRGSHPUSM649NCIS.csv", "Cass Freight Index: Shipments", "index, Jan 1990 = 1", "index points", "Cass Information Systems, Inc., via FRED", False),
    ("boxes", "PCU322211322211.csv", "PPI: Corrugated & solid fiber boxes", "index, Mar 1980 = 100", "index points", "U.S. Bureau of Labor Statistics, via FRED", False),
    ("copper", "PCOPPUSDM.csv", "Global price of copper", "$/metric ton", "$/metric ton", "International Monetary Fund, via FRED", False),
    ("jetfuel", "DJFUELUSGULF.csv", "Jet fuel, U.S. Gulf Coast", "$/gallon", "$/gallon", "U.S. Energy Information Administration, via FRED", False),
]
data, last = [], []
for key, fn, name, unit, short, src, sample in SERIES:
    rows = list(csv.DictReader(open("data/" + fn)))
    data.append({"key": key, "name": name, "unit": unit, "short": short, "source": src, "sample": sample,
                 "dates": [r["date"] for r in rows], "values": [float(r["value"]) for r in rows]})
    if not sample: last.append(rows[-1]["date"][:7])
page = open("template.html").read()
for tag, val in [("/*__DATA__*/null", json.dumps(data, separators=(",", ":"))),
                 ("/*__ENGINE__*/", open("engine.js").read()), ("/*__UPLOAD__*/", open("upload.js").read()), ("/*__APP__*/", open("app.js").read()),
                 ("/*__ASOF__*/", "FRED pull of Nov 2026; latest observations " + ", ".join(sorted(set(last))))]:
    assert tag in page, tag
    page = page.replace(tag, val)
open("index.html", "w").write(page)
print("index.html", len(page), "bytes")
